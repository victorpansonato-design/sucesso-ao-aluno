/* ==========================================================================
   Catálogo de PUSH personalizados
   --------------------------------------------------------------------------
   Estes não são avisos de calendário. Cada um nasce de um parâmetro do aluno —
   Health Score, dias sem acesso, frequência, situação financeira, etapa do
   onboarding — e só chega a quem bate na condição.

   Três regras que valem para todos os textos daqui:

   1. #NOME# é o primeiro nome, sempre. Um push que começa com o nome do aluno
      é lido; um que começa com "Prezado(a) discente" é arrastado para o lado.
   2. O push nunca acusa. "Você está com 4 faltas" vira "faltam poucas aulas
      para o limite" — o objetivo é o aluno abrir o app, não se justificar.
   3. Todo push termina em uma ação concreta e possível hoje: um botão do app,
      uma pessoa para procurar, um prazo. Aviso sem saída vira ansiedade.

   O `cooldownDays` existe porque a condição continua verdadeira depois do
   disparo. Sem ele, o aluno com duas parcelas em atraso receberia a mesma
   mensagem todo dia até pagar — e desinstalaria o aplicativo antes disso.
   ========================================================================== */

